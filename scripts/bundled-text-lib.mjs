/**
 * A TypeScript string literal holding `text` exactly.
 *
 * `JSON.stringify` rather than a template literal because the example template
 * contains backticks and `${...}` of its own, and all three files contain
 * backslashes. U+2028 and U+2029 are legal inside a JSON string but were not
 * legal inside a JavaScript string literal before ES2019, and this project
 * targets es2018, so they are escaped explicitly rather than emitted raw.
 */
const BACKSLASH = String.fromCharCode(92);
// Spelled through char codes so that THIS file contains no separator of its
// own: a raw U+2028 inside a regular expression literal is itself a syntax
// error, which is the same hazard one line down.
const SEPARATORS = [
    { char: String.fromCharCode(0x2028), escape: BACKSLASH + "u2028" },
    { char: String.fromCharCode(0x2029), escape: BACKSLASH + "u2029" },
];

export function toStringLiteral(text) {
    let literal = JSON.stringify(text);
    for (const separator of SEPARATORS) literal = literal.split(separator.char).join(separator.escape);
    if (JSON.parse(literal) !== text) {
        throw new Error("string literal does not round-trip to the source text");
    }
    return literal;
}

/** The complete contents of `entry.module` for a source file holding `text`. */
export function renderModule(entry, text) {
    return (
        `// GENERATED FILE — DO NOT EDIT. Run \`npm run bundled-text:build\`.\n` +
        `//\n` +
        `// Inlined from \`${entry.source}\`, which is the single source of truth.\n` +
        `// ${entry.why}\n` +
        `//\n` +
        `// It is inlined because Obsidian's community installer copies only \`main.js\`,\n` +
        `// \`manifest.json\` and \`styles.css\` into the plugin folder, so a modal that read\n` +
        `// this file at runtime found nothing on a store install. See\n` +
        `// \`scripts/bundled-text-lib.mjs\`; \`scripts/bundled-text-packaging.test.mjs\`\n` +
        `// fails if this constant and its source file differ by one byte.\n` +
        `export const ${entry.constant} = ${toStringLiteral(text)};\n`
    );
}
