// What the build inlines into `main.js`, and how.
//
// Obsidian's community installer copies exactly `main.js`, `manifest.json` and
// `styles.css` out of a release. Any file a modal reads at runtime therefore
// does not exist for anyone who installed from the catalogue — it exists only
// in the repo and in a local `scripts/deploy.sh` vault. Inlining the text at
// build time is the only mechanism that puts it in front of those users, the
// same conclusion `src/i18n/locales.ts` reached for translations.
//
// The repo file stays the single source of truth: nothing here is hand-copied,
// the generated module is regenerated by `npm run build`, and
// `scripts/bundled-text-packaging.test.mjs` fails if a generated constant and
// its source file disagree by one byte.
//
// This table is shared by the generator and that test on purpose: a file added
// here is generated AND gated, and one cannot be added without the other.

